def slug(v):
    return v.lower().replace(" ", "-")


def build():
    counts = {}
    # расписание: журнал k (1..13) выпускает номер i в месяц (k+i-1) начиная с 01.2026;
    # Золотой журнал (k=13) сдвинут на 9 месяцев — занимает 2027-10 … 2028-07.
    for k in range(1, 14):
        jno, jname, jslogan = JOURNALS[k - 1]
        for i in range(1, 11):
            month_idx = (k - 1) + (i - 1)
            if k == 13:
                month_idx += 9  # Золотой журнал: 21..30 → октябрь 2027 … июль 2028
            year = 2026 + month_idx // 12
            month_n = month_idx % 12 + 1
            mkey = "%d-%02d" % (year, month_n)
            mname = MONTHS_RU[month_n - 1]
            title = THEMES[k][i - 1]
            hero = HEROES[k][i - 1]
            other = OTHER[(k + i) % len(OTHER)]
            refl = REFLECTS[(k * 3 + i) % len(REFLECTS)]
            tip = TIPS[(k * 2 + i) % len(TIPS)]
            contest = CONTESTS[(k + i * 2) % len(CONTESTS)]
            cliff = FINAL_LINES[(k + i) % len(FINAL_LINES)]

            fdir = os.path.join(ROOT, mkey)
            os.makedirs(fdir, exist_ok=True)
            fname = "journal-%s-%s-issue-%02d.txt" % (jno, slug(jname), i)
            fpath = os.path.join(fdir, fname)

            line = "=" * 73
            content = "\n".join([
                line,
                "     ЖУРНАЛ «%s» · ВЫПУСК %02d/10 · ПЕРВАЯ ПОЛОСА" % (jname, i),
                "     %s %d года" % (mname.capitalize(), year),
                line,
                "   ДЕВИЗ: %s" % jslogan,
                line,
                "   ЗАГОЛОВОК: %s" % title,
                "",
                "   РАЗМЫШЛЕНИЕ. %s" % refl,
                "",
                "   ПРОГНОЗ НА МЕСЯЦ. %s" % ("Цикл 50–70 секунд: очередной шторм ожидайте "
                    "в середине месяца; запас мана ≥ 30 и рыба ≥ 40 обеспечат устойчивость льда."),
                "",
                "   ПРИЁМ И СТРАТЕГИЯ. %s" % tip,
                "",
                "   ПАРАЛЛЕЛЬ С ДРУГИМИ ИГРАМИ. %s" % other,
                "",
                "   КОНКУРС НОМЕРА. %s" % contest,
                "",
                "   СУДЬБЫ ГЕРОЕВ. %s." % hero,
                "",
                "   %s" % cliff,
                line,
                "   СТРОГО ПО СТАТЬЯМ «ЛЕДЯНОЙ ВЕЧЕРКИ»: лёд 100%, база таяния 0.7%/сек,",
                "   цена тепла 0.06%/житель, мана +8/сек, заряд −3 маны за +2.5% льда,",
                "   сеть +6 рыбы (кулдаун 0.4с), рождение при рыбе ≥ 25 каждые 6с (−15),",
                "   предел племени 12, шторм 10с × 2.5, счёт = время×10 + люди×50.",
                line,
            ])
            if k == 13:
                headline, events = GOLD_ISSUES[i - 1]
                extra = [
                    "",
                    "   ГЛАВНОЕ СОБЫТИЕ. %s" % headline,
                    "",
                ] + ["   СОБЫТИЕ. %s" % e for e in events] + ["", line]
                content = "\n".join(content.splitlines()[:-1]) + "\n" + "\n".join(extra) + "\n"
            with open(fpath, "w", encoding="utf-8") as f:
                f.write(content)
            counts[mkey] = counts.get(mkey, 0) + 1

    readme = os.path.join(ROOT, "README.txt")
    with open(readme, "w", encoding="utf-8") as f:
        f.write("«ЛЕДЯНОЙ ПРЕСС-ЦЕНТР» — каталог журналов об игре «Ледяные человечки».\n")
        f.write("13 журналов × 10 выпусков = 130 номеров, разложенных по месяцам 2026–2028.\n")
        for m in sorted(counts):
            f.write("%s: %d выпусков\n" % (m, counts[m]))
    return counts

