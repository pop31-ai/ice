def article(n, title, subtitle, sections):
    lines = []
    banner = "=" * 73
    head = "        «ЛЕДЯНАЯ ВЕЧЕРКА» — НОМЕР %03d · ПЕРВАЯ ПОЛОСА" % n
    lines.append(banner)
    lines.append(head)
    lines.append(banner)
    lines.append("   " + title)
    lines.append("   " + subtitle)
    lines.append(banner)
    for s in sections:
        lines.append("")
        lines.append("   " + s[0])
        lines.append("   " + s[1])
        for row in s[2]:
            lines.append(row)
    lines.append("=" * 73)
    return "\n".join(lines)

def tbl(*rows, widths=None):
    # rows: list of lists; makes an ASCII table
    if not rows:
        return []
    cols = len(rows[0])
    res = ["+" + "+".join(["-" * 26] * cols) + "+"]
    for r in rows:
        res.append("|" + "|".join([c.ljust(26)[:26] for c in r]) + "|")
    res.append("+" + "+".join(["-" * 26] * cols) + "+")
    return res

def sec(title, text, table_rows):
    return (title, text, tbl(*table_rows))

